_AVAILABLE = {}


def _params():
    for group, rows in GROUPS.items():
        for row in rows:
            module_path, symbol, used_in = row[:3]
            requires = row[3] if len(row) > 3 else None
            target = module_path if symbol is None else f"{module_path}.{symbol}"
            yield pytest.param(
                module_path, symbol, used_in, requires, id=f"{group}:{target}"
            )


@pytest.mark.parametrize("module_path, symbol, used_in, requires", list(_params()))
def test_public_symbol_exists(module_path, symbol, used_in, requires):
    target = module_path if symbol is None else f"{module_path}.{symbol}"
    try:
        module = importlib.import_module(module_path)
        error = None
        # Inside the try: a package that imports a name lazily (e.g.
        # conin.inference.mvr) raises the optional dependency's error here.
        if symbol is not None and not hasattr(module, symbol):
            error = f"{module_path!r} has no attribute {symbol!r}"
    except Exception as exc:
        module, error = None, f"{type(exc).__name__}: {exc}"
    if error is None:
        return

    # Skip only when the failure could be caused by a missing optional dependency.
    if requires is not None:
        if requires not in _AVAILABLE:
            _AVAILABLE[requires] = _available(requires)
        if not _AVAILABLE[requires]:
            pytest.skip(f"{requires} not available")

    pytest.fail(f"cannot import {target} (used in {used_in}): {error}")
