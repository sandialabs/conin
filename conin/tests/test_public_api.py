"""Public API smoke test.

Imports every public conin symbol used by the user-facing docs and examples and
asserts that it exists. When an import path changes, update the matching rows
here in the same change, along with the docs and notebooks that use it.

Each row is ``(module_path, symbol, used_in[, requires])``:

* ``symbol`` is ``None`` when the docs reference a whole module (``automodule``).
* ``used_in`` names the files that use the symbol. It appears in the test id and
  in the failure message.
* ``requires`` (optional) names an optional dependency. The row skips instead of
  failing when that dependency is missing or broken.

The rows were generated by scanning:

* ``doc/notebooks/**/*.ipynb``: ``import``/``from ... import`` statements in code cells;
* ``doc/sphinx/*.rst``: imports in code/doctest blocks, ``auto*`` directive targets,
  and the example tables in ``examples.rst``;
* the four ``conin/examples/*.py`` modules.

``PUBLIC_API`` lists the other public entry points of each subpackage (the
documented import paths for constraints, constrained models, representations,
inference, learning, sampling and I/O). Some also appear in the scanned groups
above.
"""

import importlib

import pytest


def _available(name):
    # pytest.importorskip and conin.util.try_import only catch ImportError, but a
    # broken install (e.g. torch with missing shared libraries) raises OSError.
    try:
        importlib.import_module(name)
    except (ImportError, OSError):
        return False
    return True


